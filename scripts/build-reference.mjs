// Bundles chat-reference/* into one module the Netlify function imports,
// so the function does not depend on reading files at runtime.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../chat-reference/", import.meta.url);
const out = new URL("../netlify/functions/chat/reference.mjs", import.meta.url);

const parts = readdirSync(dir)
  .filter((name) => /\.(md|txt)$/i.test(name))
  .sort()
  .map((name) => `[From ${name}]\n${readFileSync(new URL(name, dir), "utf8").trim()}`);

const header = "// Generated by scripts/build-reference.mjs from chat-reference/. Do not edit.\n";
writeFileSync(out, `${header}export default ${JSON.stringify(parts.join("\n\n"))};\n`);
console.log(`reference: ${parts.length} files, ${parts.join("").length} chars`);
